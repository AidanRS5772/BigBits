// Writes $OUT_DIR/tuning.rs from the schema and the resolved values (docs/tuning_system.md,
// "Accessors and their two backings"). Build script only. For each knob, in schema order:
// - `resolved::<section>::<KNOB>`: its resolved value as a `pub const`, in every build;
// - `k::<section>::<knob>()`: a `const fn` returning that value in a normal build; with the `tune`
//   feature, a relaxed load of its live cell (scalars), or of its table's atomic pointer (tables:
//   `set` swaps in a leaked copy, so the accessor still returns `&'static [u32]`);
// - its entries in `PATHS`, `RESOLVED_BITS` (a table's hash), `TABLE_OF`, `TABLE_INIT`, the tune
//   build's cells, and `all_accessor_bits()`.
// F64 values are written as their bits, so a resolved value is reproduced exactly.

use super::hash::table_bits;
use super::resolve::{flat, Resolved, Value};
use super::schema_types::{Section, Ty};
use std::fmt::Write as _;

fn rust_type(ty: Ty) -> &'static str {
    match ty {
        Ty::Usize => "usize",
        Ty::U64 => "u64",
        Ty::F64 => "f64",
        Ty::Bool => "bool",
        Ty::Table { inputs: 2, .. } => "&'static crate::tuning::table::Table2",
        Ty::Table { .. } => "&'static [u32]",
    }
}

// A Rust expression of type `ty` for `v`, usable in a const context.
fn literal(ty: Ty, v: &Value) -> String {
    match (ty, v) {
        (Ty::Usize, Value::Int(x)) => format!("{x}_usize"),
        (Ty::U64, Value::Int(x)) => format!("{x}_u64"),
        (Ty::F64, Value::Float(x)) => format!("f64::from_bits({:#018x}) /* {x:?} */", x.to_bits()),
        (Ty::Bool, Value::Bool(b)) => b.to_string(),
        (Ty::Table { .. }, Value::Table(t)) => {
            let items: Vec<String> = t.iter().map(u32::to_string).collect();
            format!("&[{}]", items.join(", "))
        }
        (ty, v) => panic!("no literal for {v:?} as {ty:?}; step functions arrive with Phase 2"),
    }
}

// The accessor body of a tune build.
fn from_cell(ty: Ty, i: usize, table: usize) -> String {
    let load = format!("crate::tuning::CELLS[{i}].load(::core::sync::atomic::Ordering::Relaxed)");
    match ty {
        Ty::Usize => format!("{load} as usize"),
        Ty::U64 => load,
        Ty::F64 => format!("f64::from_bits({load})"),
        Ty::Bool => format!("{load} != 0"),
        Ty::Table { inputs: 2, .. } => format!("crate::tuning::table_cell({table})"),
        Ty::Table { .. } => format!("crate::tuning::table_cell({table}).t"),
    }
}

// The accessor's value as bits, for `all_accessor_bits`.
fn to_bits(ty: Ty, call: &str) -> String {
    match ty {
        Ty::Usize | Ty::Bool => format!("{call} as u64"),
        Ty::U64 => call.to_string(),
        Ty::F64 => format!("{call}.to_bits()"),
        Ty::Table { inputs: 2, .. } => format!("crate::tuning::hash::table_bits({call}.t)"),
        Ty::Table { .. } => format!("crate::tuning::hash::table_bits({call})"),
    }
}

fn doc_attr(text: &str) -> String {
    format!("#[doc = {text:?}]")
}

pub fn generate(schema: &'static [Section], r: &Resolved) -> String {
    let knobs = flat(schema);
    let n = knobs.len();
    // Each table knob's index among the tables.
    let mut table_of = vec![usize::MAX; n];
    let mut tables = Vec::new();
    for (i, f) in knobs.iter().enumerate() {
        if matches!(f.knob.ty, Ty::Table { .. }) {
            table_of[i] = tables.len();
            tables.push(i);
        }
    }
    let mut o = String::new();
    let w = &mut o;
    let _ = writeln!(w, "// @generated by build.rs from src/tuning/schema.rs. Do not edit.");
    let _ = writeln!(w, "/// The number of knobs, and the length of every per-knob array below.");
    let _ = writeln!(w, "pub const NKNOBS: usize = {n};");
    let _ = writeln!(w, "/// The number of table knobs.");
    let _ = writeln!(w, "pub const NTABLES: usize = {};", tables.len());
    let _ = writeln!(w, "/// Every knob's path, in schema order.");
    let paths: Vec<String> = knobs.iter().map(|f| format!("{:?}", f.path)).collect();
    let _ = writeln!(w, "pub const PATHS: [&str; NKNOBS] = [{}];", paths.join(", "));
    let _ = writeln!(w, "/// Every knob's resolved value as bits (`Value::bits`; a table's `hash::table_bits`).");
    let bits: Vec<String> = r
        .values
        .iter()
        .map(|v| match v {
            Value::Table(t) => format!("{:#x}", table_bits(t)),
            v => format!("{:#x}", v.bits().expect("a scalar or a table")),
        })
        .collect();
    let _ = writeln!(w, "pub const RESOLVED_BITS: [u64; NKNOBS] = [{}];", bits.join(", "));
    let _ = writeln!(w, "/// Each knob's index among the tables, or usize::MAX for a scalar.");
    let tof: Vec<String> = table_of.iter().map(|&t| if t == usize::MAX { "usize::MAX".into() } else { t.to_string() }).collect();
    let _ = writeln!(w, "pub const TABLE_OF: [usize; NKNOBS] = [{}];", tof.join(", "));
    let _ = writeln!(w, "/// Each table knob's resolved value, with its row index.");
    let inits: Vec<String> = tables
        .iter()
        .map(|&i| {
            let (s, k) = (knobs[i].section.name, knobs[i].knob.name.to_uppercase());
            format!("crate::tuning::table::Table2 {{ t: resolved::{s}::{k}, rows: resolved::{s}::{k}_ROWS }}")
        })
        .collect();
    let _ = writeln!(w, "pub static TABLE_INIT: [crate::tuning::table::Table2; NTABLES] = [{}];", inits.join(", "));
    let _ = writeln!(w, "/// The live scalar values of a tune build (tables' entries are unused).");
    let _ = writeln!(w, "#[cfg(feature = \"tune\")]");
    let cells: Vec<String> = r
        .values
        .iter()
        .map(|v| format!("::core::sync::atomic::AtomicU64::new({:#x})", v.bits().unwrap_or(0)))
        .collect();
    let _ = writeln!(w, "pub(crate) static CELLS: [::core::sync::atomic::AtomicU64; NKNOBS] = [{}];", cells.join(", "));
    let _ = writeln!(w, "/// The live tables of a tune build: each points at a `&'static [u32]`.");
    let _ = writeln!(w, "#[cfg(feature = \"tune\")]");
    let tcells: Vec<String> = (0..tables.len())
        .map(|j| format!("::core::sync::atomic::AtomicPtr::new(&TABLE_INIT[{j}] as *const crate::tuning::table::Table2 as *mut crate::tuning::table::Table2)"))
        .collect();
    let _ = writeln!(
        w,
        "pub(crate) static TABLE_CELLS: [::core::sync::atomic::AtomicPtr<crate::tuning::table::Table2>; NTABLES] = [{}];",
        tcells.join(", ")
    );

    // resolved::<section>::<KNOB>
    let _ = writeln!(w, "\n/// Resolved values as constants, for const contexts in tests (never in `src/utils`).");
    let _ = writeln!(w, "pub mod resolved {{");
    for s in schema {
        let _ = writeln!(w, "    pub mod {} {{", s.name);
        for (i, f) in knobs.iter().enumerate().filter(|(_, f)| f.section.name == s.name) {
            let k = f.knob;
            let _ = writeln!(w, "        {}", doc_attr(&format!("`{}`'s resolved value.", f.path)));
            let ty = if matches!(k.ty, Ty::Table { .. }) { "&[u32]" } else { rust_type(k.ty) };
            let _ = writeln!(w, "        pub const {}: {ty} = {};", k.name.to_uppercase(), literal(k.ty, &r.values[i]));
            if let (Ty::Table { inputs, .. }, Value::Table(t)) = (k.ty, &r.values[i]) {
                let rows = if inputs == 2 { super::table::row_index(t) } else { Vec::new() };
                let items: Vec<String> = rows.iter().map(u32::to_string).collect();
                let _ = writeln!(w, "        pub const {}_ROWS: &[u32] = &[{}];", k.name.to_uppercase(), items.join(", "));
            }
        }
        let _ = writeln!(w, "    }}");
    }
    let _ = writeln!(w, "}}");

    // k::<section>::<knob>()
    let _ = writeln!(w, "\n/// Knob accessors: `k::<section>::<knob>()`.");
    let _ = writeln!(w, "pub mod k {{");
    for s in schema {
        let _ = writeln!(w, "    {}", doc_attr(s.doc));
        let _ = writeln!(w, "    pub mod {} {{", s.name);
        for (i, f) in knobs.iter().enumerate().filter(|(_, f)| f.section.name == s.name) {
            let k = f.knob;
            let was = if k.old.is_empty() { String::new() } else { format!(" (was `{}`)", k.old) };
            let ty = rust_type(k.ty);
            let doc = doc_attr(&format!("`{}`{was}. {}", f.path, k.doc));
            let _ = writeln!(w, "        {doc}");
            let _ = writeln!(w, "        #[cfg(not(feature = \"tune\"))]");
            let _ = writeln!(w, "        #[inline(always)]");
            let _ = writeln!(w, "        pub const fn {}() -> {ty} {{", k.name);
            if matches!(k.ty, Ty::Table { inputs: 2, .. }) {
                let _ = writeln!(w, "            &crate::tuning::TABLE_INIT[{}]", table_of[i]);
            } else {
                let _ = writeln!(w, "            super::super::resolved::{}::{}", s.name, k.name.to_uppercase());
            }
            let _ = writeln!(w, "        }}");
            let _ = writeln!(w, "        {doc}");
            let _ = writeln!(w, "        #[cfg(feature = \"tune\")]");
            let _ = writeln!(w, "        #[inline(always)]");
            let _ = writeln!(w, "        pub fn {}() -> {ty} {{", k.name);
            let _ = writeln!(w, "            {}", from_cell(k.ty, i, table_of[i]));
            let _ = writeln!(w, "        }}");
        }
        let _ = writeln!(w, "    }}");
    }
    let _ = writeln!(w, "}}");

    let _ = writeln!(w, "\n/// Every accessor's current value as bits, in schema order.");
    let _ = writeln!(w, "pub fn all_accessor_bits() -> [u64; NKNOBS] {{");
    let calls: Vec<String> = knobs
        .iter()
        .map(|f| to_bits(f.knob.ty, &format!("k::{}::{}()", f.section.name, f.knob.name)))
        .collect();
    let _ = writeln!(w, "    [{}]", calls.join(", "));
    let _ = writeln!(w, "}}");
    o
}
